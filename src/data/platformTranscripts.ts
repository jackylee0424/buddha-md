let transcriptPayloadPromise: Promise<PlatformTranscriptPayload> | undefined;

async function readTranscriptPayload(response: Response): Promise<string> {
  if (!response.ok) {
    throw new Error(`Failed to load Platform transcript payload: ${response.status}`);
  }

  if (response.headers.get('content-encoding')?.includes('gzip')) {
    return response.text();
  }

  if (!('DecompressionStream' in globalThis)) {
    throw new Error('DecompressionStream is not available in this browser.');
  }

  const blob = await response.blob();
  const stream = blob.stream().pipeThrough(new DecompressionStream('gzip'));
  return new Response(stream).text();
}

async function loadTranscriptPayload(): Promise<PlatformTranscriptPayload> {
  if (!transcriptPayloadPromise) {
    transcriptPayloadPromise = fetch(transcriptPayloadUrl)
      .then(readTranscriptPayload)
      .then((text) => JSON.parse(text) as PlatformTranscriptPayload);
  }

  return transcriptPayloadPromise;
}

export async function loadPlatformTranscript(id: number): Promise<string[]> {
  if (import.meta.env.MODE === 'test') {
    return testFallbackTranscripts[String(id)] ?? [];
  }

  try {
    const payload = await loadTranscriptPayload();
    return payload[String(id)] ?? [];
  } catch (error) {
    if (import.meta.env.DEV) {
      console.warn('Using Platform transcript fallback payload.', error);
    }
    return testFallbackTranscripts[String(id)] ?? [];
  }
}
